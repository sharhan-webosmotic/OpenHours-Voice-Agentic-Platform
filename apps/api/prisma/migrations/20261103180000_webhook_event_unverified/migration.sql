-- A webhook event that was stored but could not be checked against the provider.
--
-- D-006's third measure re-reads the interaction from Sarvam's authenticated API before acting
-- on a webhook, and it is the measure that holds. It needs the clinic's Sarvam app id. A clinic
-- whose Sarvam settings were saved without one (the first save mints the webhook secret
-- regardless) used to have the re-read SKIPPED SILENTLY and the payload acted on, so a forged
-- webhook created a call and a transcript (Feature 3 review, I1).
--
-- Such an event is now kept and marked UNVERIFIED, and nothing is created from it. A separate
-- value rather than FAILED, so these events can be found and replayed once the app id exists,
-- and are not mixed in with events that were checked and found not to exist.
--
-- Additive: a new enum value, no row changes. ADD VALUE inside the migration's transaction is
-- allowed on PostgreSQL 12 and later because nothing in this migration uses the new value.
-- Awaiting the second-person review every migration needs.
ALTER TYPE "webhook_event_status" ADD VALUE 'UNVERIFIED';
